#!/usr/bin/env python3
"""
Synthetic-fixture precision/recall runner.

Scans benchmarks/synthetic/fixtures/ with `regula check`, joins findings
against manifest.json, and reports per-tier precision and recall on a
fully labelled (TP/FP/FN known) corpus.

This complements benchmarks/labels.json (which is real OSS but only
covers minimal/limited/agent_autonomy tiers) by providing measurable
precision and recall for the prohibited and high_risk tiers — the
ones where false negatives have legal consequences and where the
real-OSS benchmark contains zero examples.

The corpus is small (38 fixtures: 5 prohibited, 30 high-risk, 3
negative) and synthetic by design. Numbers are fixture-bound; they tell
you whether the prohibited and high_risk detectors fire on textbook
positive cases and stay quiet on textbook negative cases. They do not
generalise to "Regula's precision in the wild" — the OSS benchmark is
the right tool for that.

WHICH CONDITION THIS FILE MEASURES, AND WHY IT SAYS SO OUT LOUD
--------------------------------------------------------------
This runner calls `report.scan_files` directly with all eight opt-in
domains declared. That is the CLASSIFIER path with the domain gate
satisfied, and it is NOT what a user gets from `regula check` with no
flags. On this corpus the two disagree: high-risk recall is 16/30 here
and 10/30 on the default scan, so a fraction printed with no condition
beside it reads twenty percentage points better than the shipped
default.

`.github/workflows/benchmark.yml` runs this file and uploads its output,
so that gap used to reach a reader as a bare number. Ledger N151.
Every fraction this file prints now names its path and its gate
condition, and the other measured conditions are printed beside it from
`benchmarks/synthetic/RECALL.json`, which
`scripts/build_recall_artefact.py` generates from an actual run of each.
That is the artefact's own `_publication_rule` applied to this file's
output rather than only to prose.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from collections import defaultdict

ROOT = Path(__file__).resolve().parent
FIXTURES = ROOT / "fixtures"
MANIFEST = ROOT / "manifest.json"

RECALL_ARTEFACT = ROOT / "RECALL.json"

# The condition THIS file measures. It is not the default a user gets, and
# saying so beside every fraction is ledger N151's fix: the CI step that
# runs this file uploaded a bare `recall=53%` while `regula check` with no
# flags recalls 10/30 = 33% on the same corpus.
THIS_CONDITION_ID = "classifier/domains-declared"
THIS_CONDITION_LABEL = (
    "classifier path (report.scan_files called directly), all eight opt-in "
    "domains declared. NOT the default a user gets from `regula check`."
)

# Use Regula's own scanner
sys.path.insert(0, str(ROOT.parent.parent / "scripts"))
from report import scan_files


def print_all_conditions() -> None:
    """Print every measured condition beside the one this file just ran.

    The fractions here are READ from benchmarks/synthetic/RECALL.json, which
    scripts/build_recall_artefact.py generates by actually running each
    condition. They are quoted, not measured in this process, and the output
    says so, because a reader who cannot tell a live figure from a quoted one
    cannot tell a regression from a stale file either.
    """
    if not RECALL_ARTEFACT.exists():
        print("\n  benchmarks/synthetic/RECALL.json is missing; the other "
              "conditions cannot be shown. Run "
              "scripts/build_recall_artefact.py.")
        return
    doc = json.loads(RECALL_ARTEFACT.read_text(encoding="utf-8"))
    conditions = doc.get("conditions", {})

    print("\nEvery measured condition on this corpus, quoted from "
          "benchmarks/synthetic/RECALL.json")
    print("  (generated by scripts/build_recall_artefact.py; NOT measured in "
          "this process)")
    print(f"  {'condition':40s} {'tier':12s} {'recall':>9s}   gates")
    for cond_id, cond in sorted(conditions.items()):
        for tier, stats in sorted(cond.get("tiers", {}).items()):
            marker = " <- printed above" if cond_id == THIS_CONDITION_ID else ""
            print(f"  {cond_id:40s} {tier:12s} "
                  f"{stats['fraction']:>9s}   {cond.get('gates', '?')}"
                  f"{marker}")

    default = conditions.get("scanner/default", {}).get("tiers", {})
    high = default.get("high_risk")
    if high:
        print(f"\n  The default a user gets (scanner path, no flags) recalls "
              f"{high['fraction']} high-risk fixtures.")
    print("  A recall fraction without its path and gate condition is not a "
          "measurement:")
    print("  the same corpus scores differently on gates alone. "
          "See RECALL.json:_publication_rule.")


def artefact_disagreement(tier_stats: dict) -> list[str]:
    """The live figures for this condition against the committed artefact.

    A quoted table beside a live measurement is only useful if something
    checks that the two still describe the same tree. Takes the stats this
    run already computed rather than re-scanning, per measurement rule 1:
    instrument the real run, do not fork it.
    """
    if not RECALL_ARTEFACT.exists():
        return []
    doc = json.loads(RECALL_ARTEFACT.read_text(encoding="utf-8"))
    tiers = (doc.get("conditions", {}).get(THIS_CONDITION_ID, {})
             .get("tiers", {}))
    problems: list[str] = []
    for tier, row in sorted(tiers.items()):
        s = tier_stats.get(tier)
        if not s:
            continue
        hits, total = s["tp"], s["tp"] + s["fn"]
        if hits != row["hits"] or total != row["total"]:
            problems.append(
                f"live {THIS_CONDITION_ID} {tier} recall is {hits}/{total}, "
                f"RECALL.json records {row['fraction']}. One of them is "
                f"stale: re-run scripts/build_recall_artefact.py and commit "
                f"the result.")
    return problems


def file_to_highest_tier(findings_for_file: list[dict]) -> str:
    """Reduce a file's findings to its highest tier."""
    order = {"prohibited": 4, "high_risk": 3, "limited_risk": 2, "minimal_risk": 1, "not_ai": 0}
    if not findings_for_file:
        return "not_ai"
    return max(findings_for_file, key=lambda f: order.get(f.get("tier", "not_ai"), 0)).get("tier", "not_ai")


def evaluate(verbose: bool = True) -> dict:
    manifest = json.loads(MANIFEST.read_text())
    expectations = manifest["expectations"]

    # Run Regula against the fixture directory.
    # Activate all opt-in domains so the benchmark measures detection accuracy
    # across every Annex III category, not just auto-fingerprinted ones.
    _all_domains = {
        "employment", "medical", "finance", "biometrics",
        "education", "law_enforcement", "infrastructure", "migration",
    }
    findings = scan_files(str(FIXTURES), declared_domains=_all_domains)
    by_file: dict[str, list[dict]] = defaultdict(list)
    for f in findings:
        # `file` field is relative to the scanned project root
        rel = f.get("file", "")
        # We want just the basename to match manifest keys
        by_file[Path(rel).name].append(f)

    results = []
    tier_stats: dict[str, dict[str, int]] = defaultdict(lambda: {"tp": 0, "fp": 0, "fn": 0, "tn": 0})

    for fname, expected in expectations.items():
        actual = file_to_highest_tier(by_file.get(fname, []))
        is_negative = expected == "not_high"

        if is_negative:
            # negative fixture: any tier other than prohibited or high_risk is correct
            correct = actual not in ("prohibited", "high_risk")
            verdict = "TN" if correct else "FP"
            # FP attributed to whichever tier was wrongly fired
            if not correct:
                tier_stats[actual]["fp"] += 1
            else:
                # TN counted against both tiers we care about
                tier_stats["prohibited"]["tn"] += 1
                tier_stats["high_risk"]["tn"] += 1
        else:
            correct = actual == expected
            verdict = "TP" if correct else "FN"
            if correct:
                tier_stats[expected]["tp"] += 1
            else:
                tier_stats[expected]["fn"] += 1

        results.append({"file": fname, "expected": expected, "actual": actual, "verdict": verdict})

    if verbose:
        print(f"\n{'File':40s}  {'Expected':12s}  {'Actual':12s}  Verdict")
        print("-" * 80)
        for r in results:
            mark = "✓" if r["verdict"] in ("TP", "TN") else "✗"
            print(f"{mark} {r['file']:38s}  {r['expected']:12s}  {r['actual']:12s}  {r['verdict']}")

        print("\nPer-tier stats (TP/FP/FN/TN)")
        print(f"  CONDITION: {THIS_CONDITION_LABEL}")
        for tier in ("prohibited", "high_risk"):
            s = tier_stats[tier]
            tp, fp, fn, tn = s["tp"], s["fp"], s["fn"], s["tn"]
            prec = tp / (tp + fp) if (tp + fp) else None
            rec = tp / (tp + fn) if (tp + fn) else None
            f1 = (2 * prec * rec / (prec + rec)) if prec and rec else None
            prec_s = f"{prec*100:.0f}%" if prec is not None else "n/a"
            rec_s = f"{rec*100:.0f}%" if rec is not None else "n/a"
            f1_s = f"{f1*100:.0f}%" if f1 is not None else "n/a"
            print(f"  {tier:12s}  tp={tp}  fp={fp}  fn={fn}  tn={tn}  "
                  f"precision={prec_s}  recall={rec_s}  f1={f1_s}  "
                  f"[{THIS_CONDITION_ID}]")

        print_all_conditions()

    return {
        "results": results,
        "tier_stats": dict(tier_stats),
    }


def metrics_dict() -> dict:
    """Return per-tier precision/recall/f1 as a flat dict for tests."""
    out = evaluate(verbose=False)
    summary = {}
    for tier in ("prohibited", "high_risk"):
        s = out["tier_stats"].get(tier, {"tp": 0, "fp": 0, "fn": 0, "tn": 0})
        tp, fp, fn = s["tp"], s["fp"], s["fn"]
        prec = tp / (tp + fp) if (tp + fp) else None
        rec = tp / (tp + fn) if (tp + fn) else None
        summary[tier] = {"tp": tp, "fp": fp, "fn": fn, "tn": s.get("tn", 0), "precision": prec, "recall": rec}
    return summary


def main() -> int:
    out = evaluate()
    problems = artefact_disagreement(out["tier_stats"])
    if problems:
        # Exit non-zero rather than warn. This runner is the synthetic-recall
        # gate in .github/workflows/benchmark.yml; a gate that knows its own
        # figure contradicts the committed artefact and still returns success
        # is measurement rule 4's blank-gate-is-not-a-green-gate, inside the
        # gate itself. The repair is one command, named in the message.
        print("\nFAILED: the live measurement and RECALL.json disagree.",
              file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
